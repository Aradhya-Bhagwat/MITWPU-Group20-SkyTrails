import Foundation

enum APIError: Error {
    case invalidURL
    case unauthorized
    case invalidResponse
    case decodingError
    case serverError(String)
}

final class SkyTrailsAPIService {
    static let shared = SkyTrailsAPIService()
    private init() {}
    
    func fetchPredictions(lat: Double, lng: Double) async throws -> PredictionResponse {
        let config = try SupabaseConfig.load()
        guard let token = UserSession.shared.getAccessToken() else {
            throw APIError.unauthorized
        }
        
        // This endpoint should serve the cached data generated by the R script
        var components = URLComponents(url: config.projectURL, resolvingAgainstBaseURL: false)
        components?.path = "/functions/v1/get-hotspot-predictions"
        
        guard let url = components?.url else {
            throw APIError.invalidURL
        }
        
        var request = URLRequest(url: url)
        request.httpMethod = "POST"
        request.setValue("application/json", forHTTPHeaderField: "Content-Type")
        request.setValue("Bearer \(token)", forHTTPHeaderField: "Authorization")
        request.setValue(config.anonKey, forHTTPHeaderField: "apikey")
        
        let body: [String: Any] = ["lat": lat, "lng": lng]
        request.httpBody = try? JSONSerialization.data(withJSONObject: body)
        
        let (data, response) = try await URLSession.shared.data(for: request)
        
        guard let httpResponse = response as? HTTPURLResponse else {
            throw APIError.invalidResponse
        }
        
        if !(200...299).contains(httpResponse.statusCode) {
            let errorMsg = String(data: data, encoding: .utf8) ?? "Server returned error \(httpResponse.statusCode)"
            throw APIError.serverError(errorMsg)
        }
        
        do {
            let decoder = JSONDecoder()
            // The R script and Edge function are generating camelCase keys like 'commonName',
            // so no conversion strategy is needed.
            return try decoder.decode(PredictionResponse.self, from: data)
        } catch {
            print("DECODING ERROR: \(error)")
            throw APIError.decodingError
        }
    }
}
